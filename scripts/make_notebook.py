                "class DeepSpeechEEG(nn.Module):\n",
                "    def __init__(self, num_channels=105, hidden_size=256, num_classes=65):\n",
                "        super(DeepSpeechEEG, self).__init__()\n",
                "        self.conv1 = nn.Conv1d(num_channels, 64, kernel_size=5, stride=1, padding=2)\n",
                "        self.bn1 = nn.BatchNorm1d(64)\n",
                "        self.relu = nn.ReLU()\n",
                "        self.pool = nn.MaxPool1d(2)\n",
                "        \n",
                "        self.lstm = nn.LSTM(64, hidden_size, num_layers=2, batch_first=True, bidirectional=True)\n",
                "        self.fc = nn.Linear(hidden_size * 2, num_classes)\n",
                "        \n",
                "    def forward(self, x):\n",
                "        x = x.transpose(1, 2)\n",
                "        x = self.pool(self.relu(self.bn1(self.conv1(x))))\n",
