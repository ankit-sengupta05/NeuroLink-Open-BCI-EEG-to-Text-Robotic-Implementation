                "class EEGDataset(Dataset):\n",
                "    def __init__(self, data_dir, max_len=500):\n",
                "        self.files = glob.glob(os.path.join(data_dir, '**', '*.h5'), recursive=True)\n",
                "        self.max_len = max_len\n",
