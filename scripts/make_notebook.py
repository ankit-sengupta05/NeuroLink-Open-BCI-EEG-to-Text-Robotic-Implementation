                "def train_model(model, name, dataloader, epochs=5):\n",
                "    criterion = nn.CTCLoss(blank=0, zero_infinity=True)\n",
                "    optimizer = optim.Adam(model.parameters(), lr=1e-3)\n",
                "    \n",
                "    loss_history = []\n",
                "    model.train()\n",
                "    for epoch in range(epochs):\n",
                "        epoch_loss = 0\n",
                "        for eeg, target in dataloader:\n",
                "            batch_size = eeg.size(0)\n",
                "            # Pooling in DeepSpeech halves the time dimension\n",
                "            out_time = eeg.size(1)//2 if isinstance(model, DeepSpeechEEG) else eeg.size(1)\n",
                "            input_lengths = torch.full(size=(batch_size,), fill_value=out_time, dtype=torch.long)\n",
                "            target_lengths = torch.tensor([len(target[0])])\n",
                "            \n",
                "            optimizer.zero_grad()\n",
                "            out = model(eeg)\n",
                "            out = out.transpose(0, 1) # [time, batch, classes]\n",
                "            out = nn.functional.log_softmax(out, dim=2)\n",
                "            \n",
                "            loss = criterion(out, target, input_lengths, target_lengths)\n",
                "            loss.backward()\n",
                "            optimizer.step()\n",
                "            \n",
                "            epoch_loss += loss.item()\n",
                "            \n",
                "        avg_loss = epoch_loss / max(1, len(dataloader))\n",
                "        loss_history.append(avg_loss)\n",
                '        print(f"[{name}] Epoch {epoch+1}/{epochs} | Loss: {avg_loss:.4f}")\n',
                "        \n",
                "    torch.save(model.state_dict(), os.path.join(MODELS_DIR, f'{name}_checkpoint.pth'))\n",
                "    return loss_history\n",
